"""Every MCP tool's advertised `outputSchema` holds for the results the tool really returns.

The schemas live in `raptor/mcp/output_schemas.json`, generated by `tools/gen_mcp_output_schemas.py` from a
scripted session; this replays that session and validates each structured result against the committed file, so a tool
that stops returning a key it promised fails here. Regenerate with `--write` after a deliberate change."""
from __future__ import annotations

import asyncio
import json
import sys
import tempfile
from pathlib import Path

import jsonschema

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))

import gen_mcp_output_schemas as gen  # noqa: E402


def _schemas() -> dict:
    return json.loads((ROOT / "raptor" / "mcp" / "output_schemas.json").read_text())


def test_every_result_of_the_scripted_session_satisfies_its_schema():
    rec = gen.Recorder()
    with tempfile.TemporaryDirectory() as d:
        gen.session(rec, Path(d))
    schemas = _schemas()
    checked = 0
    for name, results in rec.seen.items():
        for result in results:
            if name in schemas:
                jsonschema.validate(result, schemas[name])
                checked += 1
    assert checked > 40
    assert set(rec.seen) - set(schemas) <= {"ping"}, "a driven tool has no schema: regenerate the file"


def test_the_committed_file_is_what_the_generator_writes():
    rec = gen.Recorder()
    with tempfile.TemporaryDirectory() as d:
        gen.session(rec, Path(d))
    assert gen.infer(rec.seen) == _schemas(), "output_schemas.json is stale: run gen_mcp_output_schemas.py --write"


def test_tools_advertise_the_schemas():
    from raptor.mcp import server, tools_model, tools_run, tools_metrics, tools_tables, tools_view  # noqa: F401
    tools = {t.name: t for t in asyncio.run(server.mcp.list_tools())}
    schemas = _schemas()
    for name, schema in schemas.items():
        if name in tools and name != "ping":
            assert tools[name].output_schema == schema, name
    assert tools["simulate"].output_schema["required"]


def test_results_for_other_models_satisfy_the_schemas_too(tmp_path):
    """The session's own models are not the only shapes: other fixtures must satisfy the same promises."""
    import shutil
    from raptor.mcp import tools_model, tools_run, tools_metrics, tools_tables, tools_view  # noqa: F401
    from raptor.mcp.server import mcp
    mcp._raptor_args = type("A", (), {"workspace": str(tmp_path), "read_only": False})()
    mcp._raptor_ws = None
    schemas = _schemas()
    rec = gen.Recorder()
    for fixture in ("TwoBlockRedundancy", "MotorDemo", "Phasing1", "HierarchyExample", "CS_Probe"):
        dst = tmp_path / f"{fixture}.rbd"
        shutil.copy(ROOT / "tests" / "golden" / fixture / "input.rbd", dst)
        mid = (rec.call("open_model", path=dst.name) or {}).get("model_id")
        assert mid, fixture
        rec.call("describe_model", model_id=mid)
        rec.call("validate_model", model_id=mid)
        rec.call("estimate_runtime", model_id=mid)
        rec.call("single_point_failures", model_id=mid)
        run = (rec.call("simulate", model_id=mid, num_runs=2) or {}).get("run_id")
        if run:
            rec.call("get_report", run_id=run, section="final_results")
    for name, results in rec.seen.items():
        for result in results:
            jsonschema.validate(result, schemas[name])
    assert {"describe_model", "simulate", "single_point_failures"} <= set(rec.seen)
