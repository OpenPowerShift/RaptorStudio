"""Generate docs/MCP.md -- the GitHub-browseable MCP server reference -- from the live server.

    .venv/bin/python tools/gen_mcp_reference.py          # rewrite docs/MCP.md
    .venv/bin/python tools/gen_mcp_reference.py --check  # exit 1 if it is stale

The tool, resource and prompt tables come from the running server, so they cannot drift; the prose
(install, client config, transports, safety) is the template below.
"""
from __future__ import annotations

import asyncio
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "docs" / "MCP.md"


def _first_line(text: str | None) -> str:
    return (text or "").strip().split("\n\n")[0].replace("\n", " ").replace("|", "\\|")


def _params(schema: dict) -> str:
    req = set(schema.get("required", []))
    names = [f"`{n}`" + ("" if n in req else "?") for n in schema.get("properties", {})]
    return ", ".join(names) or "—"


def render() -> str:
    from raptor.mcp import prompts, resources, server, tools_model, tools_data, tools_run, tools_metrics, tools_tables, tools_view, tools_svg  # noqa: F401
    tools = sorted(asyncio.run(server.mcp.list_tools()), key=lambda t: t.name)
    res = asyncio.run(server.mcp.list_resources())
    template = asyncio.run(server.mcp.list_resource_templates())
    prm = asyncio.run(server.mcp.list_prompts())

    trows = []
    for t in tools:
        a = t.annotations
        kind = "read-only" if a and a.read_only_hint else ("destructive" if a and a.destructive_hint else "writes")
        trows.append(f"| `{t.name}` | {kind} | {_first_line(t.description)} | {_params(t.input_schema or {})} |")
    rrows = [f"| `{r.uri}` | {r.mime_type} | {_first_line(r.description)} |" for r in res]
    rrows += [f"| `{r.uri_template}` | {r.mime_type} | {_first_line(r.description)} |" for r in template]
    prows = [f"| `{p.name}` | {_first_line(p.description)} | "
             f"{', '.join(f'`{x.name}`' for x in p.arguments or []) or '—'} |" for p in prm]
    return TEMPLATE.format(n_tools=len(tools), tools="\n".join(trows), resources="\n".join(rrows),
                           prompts="\n".join(prows))


