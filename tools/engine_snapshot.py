#!/usr/bin/env python3
"""Engine snapshot: our own output, pinned against our own previous output.

The real-capture tests (`test_golden_fidelity`, `test_event_log_fidelity`,
`test_sd_diff_sweep`) compare against real Raptor, so they cannot notice a
change to a model that does not match real yet. This snapshot can: for every
`.rbd` under `tests/golden/` and `tests/fixtures/` it runs the model at its
own `NumRuns` and records a SHA-256 (plus line count) of each artifact:

* ``events``   -- every run's event log
* ``eor``/``fr`` -- the End-of-Run and Final Results reports
* ``sd``       -- the `/sd` draw log (every random draw, in order)
* ``capacity`` -- capacity-plot lines (empty for most models)
* ``cost``     -- interim-cost lines, only when the model runs cost-on

A model runs with the interim-cost sink when its fixture has a real
`rpt_interim_cost*` capture, because that option changes the trajectory in
real Raptor too (see `orchestrator.py`'s module docstring). Every step is
also checked by `raptor.core.engine.invariants.InvariantChecker`. Errors (for
example a documented `NotImplementedError` guard) are recorded as the
exception type and message, so an unsupported model is pinned as well.

Pinned by `tests/unit/test_engine_snapshot.py`. Usage (repo root):

    python tools/engine_snapshot.py --write            # regenerate SNAPSHOT.toml
    python tools/engine_snapshot.py --check            # compare, list what moved
    python tools/engine_snapshot.py --dump DIR [KEY..] # write artifact text for diffing

To see WHAT moved, dump at the old commit (a `git worktree`) and at HEAD,
then `diff -r`. Regenerate only for an intended behaviour change, and name
the moved models in the commit message (CONTRIBUTING.md, commit convention).
"""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from raptor.core.engine.invariants import InvariantChecker  # noqa: E402
from raptor.core.engine.runner import run_simulation_with_reports  # noqa: E402
from raptor.core.fileio.builder import load  # noqa: E402

GOLDEN = REPO / "tests" / "golden"
FIXTURES = REPO / "tests" / "fixtures"
SNAPSHOT = GOLDEN / "SNAPSHOT.toml"
ARTIFACTS = ("events", "eor", "fr", "sd", "capacity", "cost")
#: Fixed stand-in for the reports' wall-clock header date.
DATE = "SNAPSHOT"
_COST_HEADER = re.compile(r"^(Interim Cost Report for .*?)  \w{3} \w{3} .*$")


def model_keys() -> list[str]:
    """Every snapshotted model, as a repo-relative POSIX path."""
    paths = sorted(GOLDEN.glob("*/*.rbd")) + sorted(FIXTURES.glob("*/*.rbd"))
    return [p.relative_to(REPO).as_posix() for p in paths]


def _cost_on(key: str) -> bool:
    fixture = key.split("/")[2]
    alias = {"Cust_Exhaust": "CustExhaust"}.get(fixture, fixture)
    return any((GOLDEN / alias / "legacy").glob("rpt_interim_cost*.txt"))


def run_artifacts(key: str) -> dict[str, list[str]]:
    """Run one model and return each artifact's lines."""
    cost: list[str] | None = [] if _cost_on(key) else None
    capacity: list[str] = []
    with tempfile.TemporaryDirectory() as tmp:
        sd_path = Path(tmp) / "sd.txt"
        try:
            logs, eor, fr = run_simulation_with_reports(
                load(str(REPO / key)), date=DATE, capacity_sink=capacity,
                cost_sink=cost, sim_details_path=str(sd_path),
                on_event=InvariantChecker())
        except Exception as exc:  # pinned, not hidden: see module docstring
            return {"error": [f"{type(exc).__name__}: {exc}"]}
        sd = sd_path.read_text(encoding="latin-1").splitlines() if sd_path.exists() else []
    out = {
        "events": [line for run in logs for line in run],
        "eor": eor, "fr": fr, "sd": sd, "capacity": capacity,
    }
    if cost is not None:
        # The interim-cost header carries `time.ctime()` (orchestrator.py's
        # `interim_cost_process`), so mask the date.
        out["cost"] = [_COST_HEADER.sub(r"\1  <date>", line) for line in cost]
    return out


def digest(lines: list[str]) -> str:
    h = hashlib.sha256()
    for line in lines:
        h.update(line.encode("utf-8", "surrogateescape"))
        h.update(b"\n")
    return f"{len(lines)}:{h.hexdigest()[:20]}"


def snapshot_entry(key: str) -> dict[str, str]:
    return {name: digest(lines) for name, lines in run_artifacts(key).items()}


def read_snapshot(path: Path = SNAPSHOT) -> dict[str, dict[str, str]]:
    import tomllib
    with path.open("rb") as fh:
        return tomllib.load(fh)["model"]


def write_snapshot(entries: dict[str, dict[str, str]], path: Path = SNAPSHOT) -> None:
    lines = [
        "# Engine snapshot -- generated by tools/engine_snapshot.py --write.",
        "# Each value is `<line count>:<sha256 prefix>` of one artifact of one model.",
        "# Do not edit by hand; see the script's docstring.",
        "",
    ]
    for key in sorted(entries):
        lines.append(f'[model."{key}"]')
        for name in (*ARTIFACTS, "error"):
            if name in entries[key]:
                lines.append(f'{name} = "{entries[key][name]}"')
        lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def _compute(keys: list[str], workers: int) -> dict[str, dict[str, str]]:
    if workers <= 1:
        return {k: snapshot_entry(k) for k in keys}
    from concurrent.futures import ProcessPoolExecutor
    with ProcessPoolExecutor(workers) as pool:
        return dict(zip(keys, pool.map(snapshot_entry, keys)))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--dump", type=Path, metavar="DIR")
    ap.add_argument("keys", nargs="*", help="model keys (default: all)")
    ap.add_argument("-j", "--workers", type=int, default=4)
    a = ap.parse_args()
    keys = a.keys or model_keys()

    if a.dump:
        for key in keys:
            target = a.dump / key
            target.mkdir(parents=True, exist_ok=True)
            for name, lines in run_artifacts(key).items():
                (target / f"{name}.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
        return 0

    got = _compute(keys, a.workers)
    if a.write:
        entries = read_snapshot() if a.keys and SNAPSHOT.exists() else {}
        entries.update(got)
        write_snapshot(entries)
        print(f"wrote {len(got)} models to {SNAPSHOT.relative_to(REPO)}")
        return 0

    want = read_snapshot()
    moved = [k for k in keys if want.get(k) != got[k]]
    for k in moved:
        old, new = want.get(k, {}), got[k]
        names = sorted(n for n in set(old) | set(new) if old.get(n) != new.get(n))
        print(f"{k}: " + ", ".join(f"{n} {old.get(n)} -> {new.get(n)}" for n in names))
    missing = sorted(set(want) - set(model_keys()))
    for k in missing:
        print(f"{k}: in SNAPSHOT.toml but no longer on disk")
    print(f"{len(moved) + len(missing)} of {len(keys)} models moved")
    return 1 if moved or missing else 0


if __name__ == "__main__":
    sys.exit(main())
