#!/usr/bin/env python3
"""Generate the engine design pages that are derived from the code.

Writes three pages under `docs/engine-design/`:

* `module-map.adoc`: every engine module, its size and its purpose (the
  first paragraph of its docstring), and a diagram of which run modules
  import which.
* `state-machine.adoc`: the waits an interrupt can end
  (`wait_sites.WaitSite`), what may end each (`wait_sites.WAKE_POLICY`),
  and every `InterruptReason` with the waits that accept it.
* `method-map.adoc`: every method of the block process, the cascade and
  the run driver, where it is defined and what it does.

Usage (repo root):

    python tools/gen_engine_docs.py --write   # regenerate
    python tools/gen_engine_docs.py --check   # fail if stale (CI)

Nothing here runs a simulation, so `--check` takes about a second.
"""
from __future__ import annotations

import argparse
import ast
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from raptor.core.engine.interrupts import InterruptReason  # noqa: E402
from raptor.core.engine.wait_sites import WAKE_POLICY, WaitSite  # noqa: E402

PAGES = REPO / "docs" / "engine-design"
ENGINE = REPO / "raptor" / "core" / "engine"
CORE_EXTRA = [REPO / "raptor" / "core" / "scheduler.py", REPO / "raptor" / "core" / "model.py",
              REPO / "raptor" / "core" / "rng.py"]
HEADER = "// Generated by tools/gen_engine_docs.py -- do not edit by hand.\n"

#: The modules one run passes through, in the diagram.
RUN_MODULES = [
    "runner", "step_session", "driver", "kickoff", "load", "orchestrator", "cascade_phase",
    "cascade_cold", "cascade_dependency", "cascade_status", "block_lifecycle",
    "block_env", "costs",
]


def _modules() -> list[Path]:
    return sorted(p for p in ENGINE.glob("*.py") if p.name != "__init__.py") + CORE_EXTRA


def _summary(doc: str | None) -> str:
    """The docstring's first paragraph, on one line."""
    if not doc:
        return ""
    first = doc.strip().split("\n\n")[0]
    return " ".join(first.split()).replace("|", "\\|")


def _imports(tree: ast.Module) -> set[str]:
    """Engine-level modules this module imports at run time."""
    out: set[str] = set()
    for node in tree.body:
        if isinstance(node, ast.ImportFrom) and node.module:
            if node.module.startswith("raptor.core.engine."):
                out.add(node.module.rsplit(".", 1)[1])
            elif node.module == "raptor.core.engine":
                out.update(a.name for a in node.names)
            elif node.module in ("raptor.core.scheduler", "raptor.core.model", "raptor.core.rng"):
                out.add(node.module.rsplit(".", 1)[1])
    return out


def module_map() -> str:
    rows, edges = [], []
    for path in _modules():
        tree = ast.parse(path.read_text())
        name = path.stem
        rel = path.relative_to(REPO).as_posix()
        rows.append(f"| `{rel}` | {_summary(ast.get_docstring(tree))}")
        if name in RUN_MODULES:
            edges += [(name, dep) for dep in sorted(_imports(tree)) if dep in RUN_MODULES and dep != name]
    out = [
        "= Engine module map", "", HEADER,
        "Every module of the simulation engine and its purpose (the first paragraph of its docstring).",
        "Regenerate with `python tools/gen_engine_docs.py --write`; CI fails if this page is",
        "stale.", "",
        "== How one run moves through the modules", "",
        "An arrow is a run-time import (the scheduler, which almost every module imports, is left out).",
        "The cascade and the driver keep method groups in their own modules (`cascade_*`, `kickoff`) as",
        "functions bound into the class.", "",
        "[mermaid]", "....", "flowchart TD",
    ]
    out += [f"    {a} --> {b}" for a, b in edges]
    out += ["....", "", "== Modules", "",
            '[cols="3,8",options="header"]', "|===", "| Module | Purpose"]
    out += rows
    out += ["|===", ""]
    return "\n".join(out)


def _wait_site_comments() -> dict[str, str]:
    """`WaitSite` member -> its `#:` comment in wait_sites.py."""
    lines = (ENGINE / "wait_sites.py").read_text().splitlines()
    found, buffer = {}, []
    for line in lines:
        s = line.strip()
        if s.startswith("#:"):
            buffer.append(s[2:].strip())
            continue
        m = re.match(r"([A-Z_]+) = \"(\w+)\"", s)
        if m and buffer:
            found[m.group(2)] = " ".join(buffer).replace("|", "\\|")
        buffer = []
    return found


def _reason_groups() -> dict[str, str]:
    """`InterruptReason` value -> the group comment above it."""
    lines = (ENGINE / "interrupts.py").read_text().splitlines()
    out, group, inside = {}, "", False
    for line in lines:
        s = line.strip()
        if s.startswith("class InterruptReason"):
            inside = True
            continue
        if not inside:
            continue
        if s.startswith("#"):
            group = s.lstrip("# ").rstrip(".")
        m = re.match(r"[A-Z_]+ = \"([\w-]+)\"", s)
        if m:
            out[m.group(1)] = group
        if line and not line.startswith(" ") and not s.startswith("class"):
            break
    return out


def state_machine() -> str:
    where = _wait_site_comments()
    out = [
        "= Block state machine: waits and wakes", "", HEADER,
        "An ordinary block's process (`BlockProcess`) waits at one of the sites below; an interrupt",
        "(`Scheduler.interrupt`, delivered as a `Wake`) can end the wait early. `wait_sites.WAKE_POLICY`",
        "says what may end each wait. Which of these combinations the models actually reach is on",
        "xref:state-coverage.adoc[Block state coverage]. Regenerate with",
        "`python tools/gen_engine_docs.py --write`.", "",
        "== Wait sites", "",
        '[cols="2,5,1,4,3",options="header"]', "|===",
        "| Site | Where | Timer | Reasons that end it | Condition",
    ]
    for site in WaitSite:
        pol = WAKE_POLICY[site]
        reasons = "any (the wake is not read)" if pol.reasons is None else (
            ", ".join(f"`{r}`" for r in sorted(pol.reasons)) or "none")
        out.append(f"| `{site}` | {where.get(str(site), '')} | {'yes' if pol.timer else 'no'} | "
                   f"{reasons} | {pol.note}")
    out += ["|===", "", "== Interrupt reasons", "",
            "Each reason with the sites whose policy names it. Sites that do not read their wake",
            "(policy \"any\") accept every reason and are not listed. A reason with no wait site is",
            "delivered to another process (a cold-standby switch, a PM trigger, a dependent block) or",
            "only recorded on the block.", "",
            '[cols="2,3,5",options="header"]', "|===", "| Reason | Group | Accepted at"]
    groups = _reason_groups()
    for reason in InterruptReason:
        sites = [f"`{s}`" for s in WaitSite if WAKE_POLICY[s].reasons and reason in WAKE_POLICY[s].reasons]
        out.append(f"| `{reason}` | {groups.get(str(reason), '')} | {', '.join(sites) or '_no wait site_'}")
    out += ["|===", ""]
    return "\n".join(out)



#: (class, [files whose methods or `self`-taking functions belong to it]).
CLASSES = [
    ("BlockProcess", ["block_lifecycle.py"]),
    ("_Cascade", ["orchestrator.py", "cascade_phase.py", "cascade_cold.py", "cascade_dependency.py",
                  "cascade_status.py"]),
    ("SingleRunDriver", ["driver.py", "kickoff.py"]),
]


def _methods(cls: str, files: list[str]):
    for file_name in files:
        tree = ast.parse((ENGINE / file_name).read_text())
        for node in tree.body:
            if isinstance(node, ast.ClassDef) and node.name == cls:
                for m in node.body:
                    if isinstance(m, ast.FunctionDef):
                        yield file_name, m
            elif isinstance(node, ast.FunctionDef) and node.args.args and node.args.args[0].arg == "self":
                yield file_name, node


def method_map() -> str:
    out = [
        "= Method map", "", HEADER,
        "Every method of the block process, the cascade and the run driver: where it is defined and",
        "what it does (the first sentence of its docstring).",
        "Regenerate with `python tools/gen_engine_docs.py --write`.", "",
    ]
    for cls, files in CLASSES:
        out += [f"== `{cls}`", "", '[cols="3,2,7",options="header"]', "|===",
                "| Method | Defined in | Summary"]
        for file_name, m in _methods(cls, files):
            summary = _summary(ast.get_docstring(m) or "")
            if len(summary) > 160:
                summary = summary[:157].rsplit(" ", 1)[0] + " ..."
            out.append(f"| `{m.name}` | `{file_name}` | {summary}")
        out += ["|===", ""]
    return "\n".join(out)


GENERATED = {"module-map.adoc": module_map, "state-machine.adoc": state_machine, "method-map.adoc": method_map}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    a = ap.parse_args()
    stale = []
    for name, build in GENERATED.items():
        text = build()
        path = PAGES / name
        if a.write:
            path.write_text(text)
            print(f"wrote {path.relative_to(REPO)}")
        elif not path.exists() or path.read_text() != text:
            stale.append(name)
    for name in stale:
        print(f"STALE: docs/engine-design/{name} -- run gen_engine_docs.py --write")
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
