#!/usr/bin/env python3
"""The block state-coverage matrix.

Runs every snapshot model (`tools/engine_snapshot.py`'s corpus) with a
`block_env.StateObserver` installed and records, for ordinary blocks
(`BlockProcess`):

* each `WaitSite` x wake reason that occurred (a reason, or "(timer)" when
  the wait ran its full length), and
* each status transition a block made itself (`old -> new`),

with how many models reached it and one example. It writes
`docs/engine-design/state-coverage.adoc`. The empty cells are the
states and events no model exercises.

Usage (repo root):

    python tools/state_coverage.py --write -j 8   # regenerate the page
    python tools/state_coverage.py --check -j 8   # fail if coverage shrank

`--check` fails when a cell the page lists is no longer reached: coverage
must not shrink without the page being regenerated on purpose, in the same
PR that explains why. New cells are reported but do not fail.
"""
from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))
sys.path.insert(0, str(REPO / "tools"))

from engine_snapshot import model_keys, run_artifacts  # noqa: E402

from raptor.core.engine.block_env import observing  # noqa: E402
from raptor.core.engine.wait_sites import WAKE_POLICY, WaitSite  # noqa: E402

PAGE = REPO / "docs" / "engine-design" / "state-coverage.adoc"
TIMER = "(timer)"
Cell = tuple[str, str]


class _Recorder:
    """A `StateObserver` that records which cells a model reaches."""

    def __init__(self) -> None:
        self.wakes: set[Cell] = set()
        self.transitions: set[Cell] = set()

    def on_wake(self, block, site, wake) -> None:
        self.wakes.add((str(site), TIMER if wake is None else str(wake.reason)))

    def on_transition(self, block, old, new, comment) -> None:
        self.transitions.add((old.name, new.name))


def _record(key: str) -> tuple[str, set[Cell], set[Cell]]:
    recorder = _Recorder()
    with observing(recorder):
        run_artifacts(key)
    return key, recorder.wakes, recorder.transitions


def collect(workers: int) -> tuple[dict[Cell, list[str]], dict[Cell, list[str]]]:
    keys = model_keys()
    if workers <= 1:
        results = [_record(k) for k in keys]
    else:
        from concurrent.futures import ProcessPoolExecutor
        with ProcessPoolExecutor(workers) as pool:
            results = list(pool.map(_record, keys))
    wakes: dict[Cell, list[str]] = defaultdict(list)
    transitions: dict[Cell, list[str]] = defaultdict(list)
    for key, w, t in results:
        for cell in w:
            wakes[cell].append(key)
        for cell in t:
            transitions[cell].append(key)
    return wakes, transitions


def _allowed(cell: Cell) -> bool:
    policy = WAKE_POLICY[WaitSite(cell[0])]
    if cell[1] == TIMER:
        return policy.timer
    return policy.reasons is None or cell[1] in policy.reasons


def _model_name(key: str) -> str:
    return Path(key).parent.name


def render(wakes: dict[Cell, list[str]], transitions: dict[Cell, list[str]]) -> str:
    n_models = len(model_keys())
    out = [
        "= Block state coverage",
        "",
        "// Generated by tools/state_coverage.py -- do not edit by hand.",
        "",
        f"Which waits and status changes of an ordinary block (`BlockProcess`) the {n_models} snapshot models reach.",
        "Regenerate with `python tools/state_coverage.py --write -j 8`;",
        "`--check` fails if a listed cell is no longer reached.",
        "The wait sites are `wait_sites.WaitSite`. \"(timer)\" means the wait ran its full length.",
        "",
        "== Wakes by wait site",
        "",
        "One row per way a wait can end that `wait_sites.WAKE_POLICY` allows, with how many models reach it.",
        "A row with 0 models is allowed but never exercised. For a site that ignores what woke it",
        "(policy \"any\"), the rows are the wakes that actually arrived.",
        "",
        '[cols="2,3,1,2,4",options="header"]',
        "|===",
        "| Wait site | Ends by | Models | Example | Policy note",
    ]
    for site in WaitSite:
        policy = WAKE_POLICY[site]
        observed = {cell[1] for cell in wakes if cell[0] == str(site)}
        allowed = ({TIMER} if policy.timer else set()) | set(policy.reasons or ())
        ends = sorted(allowed | observed, key=lambda e: (e != TIMER, e))
        if not ends:
            out.append(f"| `{site}` | _nothing reaches it_ | 0 | | {policy.note}")
        note = policy.note if policy.reasons is not None else ("any: " + policy.note).rstrip(": ")
        for end in ends:
            models = sorted(wakes.get((str(site), end), []))
            example = _model_name(models[0]) if models else ""
            out.append(f"| `{site}` | {end} | {len(models)} | {example} | {note}")
            note = ""
    out += [
        "|===",
        "",
        "== Status changes a block makes itself",
        "",
        '[cols="2,2,1,3",options="header"]',
        "|===",
        "| From | To | Models | Example",
    ]
    for cell in sorted(transitions):
        models = sorted(transitions[cell])
        out.append(f"| {cell[0]} | {cell[1]} | {len(models)} | {_model_name(models[0])}")
    out += ["|===", ""]
    return "\n".join(out)


_ROW = re.compile(r"^\| `(\w+)` \| (.+?) \| (\d+) \|")
_TRANSITION_ROW = re.compile(r"^\| (\w+) \| (\w+) \| (\d+) \|")


def _cells(text: str) -> tuple[set[Cell], set[Cell]]:
    wakes, transitions = set(), set()
    section = None
    for line in text.splitlines():
        if line.startswith("== "):
            section = line
            continue
        if section and "Wakes" in section and (m := _ROW.match(line)) and int(m.group(3)) > 0:
            wakes.add((m.group(1), m.group(2)))
        elif section and "Status" in section and (m := _TRANSITION_ROW.match(line)):
            transitions.add((m.group(1), m.group(2)))
    return wakes, transitions


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    ap.add_argument("-j", "--workers", type=int, default=4)
    a = ap.parse_args()
    wakes, transitions = collect(a.workers)
    text = render(wakes, transitions)
    if a.write:
        outside = sorted(cell for cell in wakes if not _allowed(cell))
        if outside:
            print(f"refusing to write: cells outside wait_sites.WAKE_POLICY: {outside}")
            return 1
        PAGE.write_text(text)
        print(f"wrote {PAGE.relative_to(REPO)}: {len(wakes)} wake cells, {len(transitions)} transitions")
        return 0
    outside = sorted(cell for cell in wakes if not _allowed(cell))
    for cell in outside:
        print(f"OUTSIDE POLICY: a model reaches {cell}, which wait_sites.WAKE_POLICY does not allow")
    old_wakes, old_transitions = _cells(PAGE.read_text())
    new_wakes, new_transitions = _cells(text)
    lost = sorted(old_wakes - new_wakes) + sorted(old_transitions - new_transitions)
    gained = sorted(new_wakes - old_wakes) + sorted(new_transitions - old_transitions)
    for cell in gained:
        print(f"new cell (regenerate the page to record it): {cell}")
    for cell in lost:
        print(f"LOST: {cell} is no longer reached by any model")
    return 1 if lost or outside else 0


if __name__ == "__main__":
    raise SystemExit(main())
